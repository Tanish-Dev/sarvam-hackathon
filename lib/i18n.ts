export const BUILTIN: Partial<Record<string, Dict>> = { "en-IN": en, "hi-IN": hi, "mr-IN": mr };

export function fill(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Accept a machine-translated dictionary only where placeholders survived. */
export function mergeTranslated(values: string[]): Dict {
  const keys = Object.keys(en) as UiKey[];
  const out = { ...en };
  keys.forEach((k, i) => {
    const v = values[i];
    const need = en[k].match(/\{\w+\}/g) ?? [];
    if (typeof v === "string" && v.trim() && need.every((p) => v.includes(p))) out[k] = v.trim();
  });
  return out;
}
